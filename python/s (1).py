from datetime import datetime      # импортируем класс datetime для работы с датой и временем
from math import sqrt              # импортируем функцию sqrt (квадратный корень) из модуля math

def main(**kwargs):                 # определяем функцию main, которая принимает произвольное количество именованных аргументов
    for key in kwargs.items():      # перебираем все пары (ключ, значение) словаря kwargs
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)  # вычисляем длину вектора по формуле sqrt(x^2 + y^2)
        print(result)               # выводим результат вычисления

if __name__ == '__main__':          # проверка, что программа запущена напрямую, а не импортирована как модуль
    start_time = datetime.now()     # сохраняем текущее время перед выполнением функции
    main(                           # вызываем функцию main, передавая ей несколько аргументов-списков
        one=[10, 3],
        two=[5, 4],
        three=[15, 13],
        four=[93, 53],
        five=[133, 15]
    )
    time_costs = datetime.now() - start_time   # вычисляем время выполнения программы
    print(f"Время выполнения программы - {time_costs}")  # выводим затраченное время
